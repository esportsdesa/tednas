-- Migrasi 13: TAUTAN KOMUNITAS untuk ToT (lomba antarkomunitas mengumpulkan tim, permintaan user 17 Nov 2026).
-- Jalankan SETELAH migration-12-perbaiki.sql. Aman dijalankan ulang.
--
--  * ToT (papan skor, lomba) hanya ada di MZone. esportsdesa.id tetap hanya jalur pendaftaran: di sini cuma tautan
--    pendaftaran per komunitas + pencatatan, dan tab Komunitas di halaman admin untuk membuat tautannya.
--  * Admin membuat komunitas → tautannya esportsdesa.id/k/<id> (dialihkan ke daftar?k=<id>).
--  * Tim yang mendaftar lewat tautan itu tercatat di tednas_tim.komunitas_id (tednas_daftar menerima p_komunitas).
--  * Tim yang TIDAK lewat tautan komunitas (atau lewat kode tak dikenal / komunitas nonaktif) masuk komunitas
--    bawaan, MZone Tour (user 17 Nov: "yang ngga ada di komunitas manapun, masuknya ke komunitas mzonetour").
--    Tim lama yang belum punya komunitas ikut dipindah ke sana oleh migrasi ini. Pendaftaran tidak pernah gagal
--    karena kode komunitas.
--  * Admin bisa memindahkan tim ke komunitas lain (koreksi) langsung di tabel tednas_tim (RLS admin yang sudah ada).
--    Kolom komunitas_id tidak ikut drive_versi dan sidik AI, jadi tidak memicu tulis ulang Sheet atau cek ulang AI.

create table if not exists public.tednas_komunitas (
  id int generated by default as identity primary key,
  nama text not null check (char_length(trim(nama)) between 2 and 80),
  kota text not null default '' check (char_length(kota) <= 80),        -- kota/kabupaten basis komunitas
  provinsi text not null default '' check (char_length(provinsi) <= 80),
  pic_nama text not null default '' check (char_length(pic_nama) <= 80),
  pic_wa text not null default '' check (pic_wa = '' or pic_wa ~ '^628[0-9]{7,12}$'),
  aktif boolean not null default true,
  bawaan boolean not null default false,   -- satu-satunya komunitas bawaan (MZone Tour)
  created_at timestamptz not null default now()
);
create unique index if not exists tednas_komunitas_satu_bawaan on public.tednas_komunitas (bawaan) where bawaan;
insert into public.tednas_komunitas (nama, bawaan)
  select 'MZone Tour', true where not exists (select 1 from public.tednas_komunitas where bawaan);
alter table public.tednas_komunitas enable row level security;
revoke all on public.tednas_komunitas from anon, authenticated;
grant select, insert, update on public.tednas_komunitas to authenticated;
drop policy if exists komunitas_admin on public.tednas_komunitas;
create policy komunitas_admin on public.tednas_komunitas for all to authenticated
  using (public.tednas_is_admin()) with check (public.tednas_is_admin());

alter table public.tednas_tim add column if not exists komunitas_id int references public.tednas_komunitas(id) on delete set null;
create index if not exists tednas_tim_komunitas on public.tednas_tim (komunitas_id) where komunitas_id is not null;
-- Tim lama tanpa komunitas → MZone Tour.
update public.tednas_tim set komunitas_id = (select id from public.tednas_komunitas where bawaan) where komunitas_id is null;

-- Papan skor publik tidak dibuat di esportsdesa.id (ToT di MZone). Versi awal migrasi ini sempat membuatnya.
drop function if exists public.tednas_komunitas_papan();

-- ========== PUBLIK ==========
-- Nama komunitas untuk spanduk di formulir daftar ("Kamu mendaftar lewat komunitas …"). Null bila tidak ada/nonaktif.
-- Tanpa data PIC.
create or replace function public.tednas_komunitas_info(p_id int)
returns json language sql stable security definer set search_path = public as $$
  select json_build_object('id', k.id, 'nama', k.nama, 'kota', k.kota, 'provinsi', k.provinsi)
  from public.tednas_komunitas k where k.id = p_id and k.aktif;
$$;

-- ========== ADMIN ==========
create or replace function public.tednas_komunitas_admin()
returns json language plpgsql stable security definer set search_path = public as $$
begin
  if not public.tednas_is_admin() then raise exception 'BUKAN_ADMIN'; end if;
  return (select coalesce(json_agg(x order by x.id), '[]'::json) from (
    select k.*, count(t.id) as mendaftar,
      count(t.id) filter (where t.status = 'terverifikasi') as terverifikasi,
      count(t.id) filter (where t.status = 'menunggu') as menunggu
    from public.tednas_komunitas k left join public.tednas_tim t on t.komunitas_id = k.id
    group by k.id) x);
end $$;

-- ========== PENDAFTARAN: sama dengan migrasi 8, ditambah p_komunitas ==========
begin;
drop function if exists public.tednas_daftar(text,text,text,text,text,text,text,text,text,jsonb,text);
create or replace function public.tednas_daftar(
  p_nama_tim text, p_wa text,
  p_prov_kode text, p_provinsi text, p_kab_kode text, p_kabupaten text,
  p_kecamatan text, p_desa_kode text, p_desa text,
  p_pemain jsonb, p_captcha text, p_komunitas int default null
) returns json language plpgsql security definer set search_path = public, extensions as $$
declare
  v_wa text := regexp_replace(coalesce(p_wa,''), '[^0-9]', '', 'g');
  v_kode text;
  v_secret text;
  v_jawab text;
  v_tim uuid;
  v_jumlah int := case when jsonb_typeof(p_pemain) = 'array' then jsonb_array_length(p_pemain) else 0 end;
  v_p jsonb;
  v_berkas text[] := '{}';
  v_bersih jsonb := '[]'::jsonb;
  v_dok text; v_ml text; v_ig1 text; v_ig2 text; v_izin text;
  v_komunitas int;
begin
  if not (select pendaftaran_buka from public.tednas_pengaturan where id = 1) then
    raise exception 'PENDAFTARAN_TUTUP';
  end if;
  if v_wa like '08%' then v_wa := '62' || substr(v_wa, 2); end if;
  if v_wa !~ '^628[0-9]{7,12}$' then raise exception 'WA_TIDAK_VALID'; end if;

  if coalesce(p_prov_kode,'') !~ '^[0-9]{2}$'
     or coalesce(p_kab_kode,'') !~ '^[0-9]{2}\.[0-9]{2}$'
     or coalesce(p_desa_kode,'') !~ '^[0-9]{2}\.[0-9]{2}\.[0-9]{2}\.[0-9]{4}$'
     or left(p_desa_kode, 5) <> p_kab_kode or left(p_kab_kode, 2) <> p_prov_kode then
    raise exception 'WILAYAH_TIDAK_VALID';
  end if;

  if v_jumlah not in (5, 6) then raise exception 'PEMAIN_TIDAK_LENGKAP'; end if;
  for v_p in select * from jsonb_array_elements(p_pemain) loop
    if char_length(trim(coalesce(v_p->>'nama',''))) not between 2 and 80 then
      raise exception 'PEMAIN_TIDAK_LENGKAP';
    end if;
    if coalesce(v_p->>'dokumen_jenis','') not in ('KTP','KK','Suket RT/RW','Kartu Pelajar') then
      raise exception 'DOKUMEN_TIDAK_ADA';
    end if;
    v_dok := public.tednas_berkas_sah(v_p->>'dokumen_path', true);
    if v_dok is null then raise exception 'DOKUMEN_TIDAK_ADA'; end if;
    v_ml := public.tednas_berkas_sah(v_p->>'profil_ml_path', false);
    if v_ml is null then raise exception 'PROFIL_ML_TIDAK_ADA'; end if;
    v_ig1 := public.tednas_berkas_sah(v_p->>'follow_esports_path', false);
    v_ig2 := public.tednas_berkas_sah(v_p->>'follow_ppdt_path', false);
    if v_ig1 is null or v_ig2 is null then raise exception 'FOLLOW_TIDAK_ADA'; end if;
    v_izin := null;
    if nullif(v_p->>'izin_path','') is not null then
      v_izin := public.tednas_berkas_sah(v_p->>'izin_path', true);
      if v_izin is null then raise exception 'IZIN_TIDAK_ADA'; end if;
    end if;
    v_berkas := v_berkas || v_dok || v_ml || v_ig1 || v_ig2;
    if v_izin is not null then v_berkas := v_berkas || v_izin; end if;
    v_bersih := v_bersih || jsonb_build_object('nama', trim(v_p->>'nama'), 'dokumen_jenis', v_p->>'dokumen_jenis',
      'dokumen_path', v_dok, 'profil_ml_path', v_ml, 'follow_esports_path', v_ig1, 'follow_ppdt_path', v_ig2, 'izin_path', v_izin);
  end loop;

  -- Satu berkas tidak boleh dipakai dua kali, baik di tim ini maupun tim lain.
  if (select count(distinct b) from unnest(v_berkas) b) <> cardinality(v_berkas)
     or exists (select 1 from public.tednas_pemain t
                where t.dokumen_path = any(v_berkas) or t.profil_ml_path = any(v_berkas) or t.izin_path = any(v_berkas)
                   or t.follow_esports_path = any(v_berkas) or t.follow_ppdt_path = any(v_berkas)) then
    raise exception 'DOKUMEN_TIDAK_ADA';
  end if;

  if exists (select 1 from public.tednas_tim where wa_kapten = v_wa) then
    raise exception 'WA_SUDAH_ADA';
  end if;

  select turnstile_secret into v_secret from public.tednas_rahasia where id = 1;
  if v_secret is null then raise exception 'CAPTCHA_BELUM_SIAP'; end if;
  if coalesce(p_captcha,'') = '' then raise exception 'CAPTCHA_GAGAL'; end if;
  select content into v_jawab from extensions.http_post(
    'https://challenges.cloudflare.com/turnstile/v0/siteverify',
    'secret=' || extensions.urlencode(v_secret) || '&response=' || extensions.urlencode(p_captcha),
    'application/x-www-form-urlencoded');
  if coalesce((v_jawab::json->>'success')::boolean, false) is not true then
    raise exception 'CAPTCHA_GAGAL';
  end if;

  -- Tautan komunitas (migrasi 13). Tanpa tautan, kode tak dikenal, atau komunitas nonaktif → komunitas bawaan (MZone Tour).
  select id into v_komunitas from public.tednas_komunitas where id = p_komunitas and aktif;
  if v_komunitas is null then
    select id into v_komunitas from public.tednas_komunitas where bawaan;
  end if;

  v_kode := 'TED-' || lpad(nextval('public.tednas_kode_seq')::text, 5, '0');
  insert into public.tednas_tim (kode, nama_tim, nama_kapten, wa_kapten, prov_kode, provinsi,
    kab_kode, kabupaten, kecamatan, desa_kode, desa, komunitas_id)
  values (v_kode, trim(p_nama_tim), v_bersih->0->>'nama', v_wa, p_prov_kode, left(p_provinsi,80),
    p_kab_kode, left(p_kabupaten,80), left(coalesce(p_kecamatan,''),80), p_desa_kode, left(p_desa,80), v_komunitas)
  returning id into v_tim;

  insert into public.tednas_pemain (tim_id, urutan, nama, dokumen_jenis, dokumen_path, profil_ml_path,
    follow_esports_path, follow_ppdt_path, izin_path)
    select v_tim, u::int, e->>'nama', e->>'dokumen_jenis', e->>'dokumen_path', e->>'profil_ml_path',
      e->>'follow_esports_path', e->>'follow_ppdt_path', nullif(e->>'izin_path','')
    from jsonb_array_elements(v_bersih) with ordinality as x(e, u);

  return json_build_object('kode', v_kode, 'komunitas', v_komunitas);
exception
  when unique_violation then
    if sqlerrm like '%wa_kapten%' then raise exception 'WA_SUDAH_ADA'; end if;
    if sqlerrm like '%_path_%' then raise exception 'DOKUMEN_TIDAK_ADA'; end if;
    raise;
end;
$$;
revoke all on function public.tednas_daftar(text,text,text,text,text,text,text,text,text,jsonb,text,int) from public;
grant execute on function public.tednas_daftar(text,text,text,text,text,text,text,text,text,jsonb,text,int) to anon, authenticated;
commit;

revoke all on function public.tednas_komunitas_info(int) from public;
revoke all on function public.tednas_komunitas_admin() from public, anon;
grant execute on function public.tednas_komunitas_info(int) to anon, authenticated;
grant execute on function public.tednas_komunitas_admin() to authenticated;
